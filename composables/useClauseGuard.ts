import { ref, computed } from 'vue';
import type { ScanContractResponse, OverrunParams, OverrunMetrics, NegotiationPosture } from '~/types';
import type { SampleContract } from '~/server/data/sampleContracts';
import { useBilling } from './useBilling';

// Shared state
const rawText = ref<string>('');
const contractTitle = ref<string>('Commercial Agreement');
const contractType = ref<string>('msa');
const isAnalyzing = ref<boolean>(false);
const auditResult = ref<ScanContractResponse | null>(null);
const selectedPosture = ref<NegotiationPosture>('firm');
const activeFlagId = ref<string | null>(null);

const overrunParams = ref<OverrunParams>({
  baseFee: 12000,
  estimatedHours: 80,
  targetHourlyRate: 150,
  includedRevisions: 2,
  anticipatedRevisions: 5,
  clientReviewWindowDays: 5
});

const overrunMetrics = ref<OverrunMetrics | null>(null);

export function useClauseGuard() {
  const billing = useBilling();

  const characterCount = computed(() => rawText.value.length);
  const wordCount = computed(() => (rawText.value.trim() ? rawText.value.trim().split(/\s+/).length : 0));
  const canAnalyze = computed(() => characterCount.value >= 100 && !isAnalyzing.value);

  async function analyzeContract() {
    if (!canAnalyze.value) return;

    // Check if free user is already out of quota
    if (billing.isQuotaExhausted.value) {
      billing.openUpgradeModal();
      return;
    }

    isAnalyzing.value = true;
    try {
      const data = await $fetch<ScanContractResponse>('/api/audit/scan', {
        method: 'POST',
        body: {
          title: contractTitle.value,
          contractType: contractType.value,
          rawText: rawText.value
        }
      });

      auditResult.value = data;
      if (data.flags.length > 0) {
        activeFlagId.value = data.flags[0].id;
      }

      // Update local billing state
      billing.usageCount.value = data.customer.usageCount;
      billing.quotaLimit.value = data.customer.quotaLimit;
      billing.tier.value = data.customer.tier;
    } catch (err: any) {
      if (err.statusCode === 402) {
        billing.openUpgradeModal();
      } else {
        console.error('Audit execution error:', err);
      }
    } finally {
      isAnalyzing.value = false;
    }
  }

  function loadSampleContract(sample: SampleContract) {
    rawText.value = sample.rawText;
    contractTitle.value = sample.title;
    contractType.value = sample.contractType;
    auditResult.value = null;
  }

  function resetEditor() {
    rawText.value = '';
    contractTitle.value = 'Commercial Agreement';
    auditResult.value = null;
  }

  function generateMarkdownReport(): string {
    if (!auditResult.value) return '';

    const res = auditResult.value;
    const isPro = billing.isPro.value;
    const dateStr = new Date().toLocaleDateString('en-US', { dateStyle: 'long' });

    let md = `# Executive Contract Risk Redline Briefing\n\n`;
    md += `**Document Title:** ${res.title}  \n`;
    md += `**Contract Type:** ${res.contractType.toUpperCase()}  \n`;
    md += `**Date of Audit:** ${dateStr}  \n`;
    md += `**Protection Index:** ${res.protectionIndex}/100 (${res.riskLevel} Risk Exposure)  \n`;
    md += `**Audited Words:** ${res.wordCount} words  \n\n`;

    if (!isPro) {
      md += `> [!NOTE]\n> Evaluated with ClauseGuard Studio Free Evaluation. Upgrade to Pro for unwatermarked certified exports.\n\n`;
    }

    md += `## 1. Executive Summary\n`;
    md += `- **Critical Predatory Violations:** ${res.summary.criticalCount}\n`;
    md += `- **Warning Commercial Traps:** ${res.summary.warningCount}\n`;
    md += `- **Verified Protective Clauses:** ${res.summary.safeCount}\n\n`;

    md += `## 2. Flagged Predatory Clauses & Protective Redlines\n\n`;

    res.flags.forEach((flag, index) => {
      md += `### Clause #${index + 1}: ${flag.name} (${flag.severity})\n`;
      md += `**Original Clause:**\n> "${flag.originalText}"\n\n`;
      md += `**Commercial Legal Advisory:**\n${flag.explanation}\n\n`;
      md += `**Proposed Counter-Clause (Firm Commercial Standard):**\n\`\`\`text\n${flag.counterClauseFirm}\n\`\`\`\n\n`;
      md += `**Collaborative Phrasing:**\n> ${flag.counterClauseCollaborative}\n\n`;
      md += `---\n\n`;
    });

    md += `\n*Generated by ClauseGuard Studio — Autonomous Contract Risk Auditor & Redliner*\n`;
    return md;
  }

  return {
    rawText,
    contractTitle,
    contractType,
    isAnalyzing,
    auditResult,
    selectedPosture,
    activeFlagId,
    overrunParams,
    overrunMetrics,
    characterCount,
    wordCount,
    canAnalyze,
    analyzeContract,
    loadSampleContract,
    resetEditor,
    generateMarkdownReport
  };
}
